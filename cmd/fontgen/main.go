// fontgen rasterizes TrueType fonts into the anti-aliased 4-bit bitmap fonts
// used by package gfx (see gfx/font.go for the format).
//
// It runs on the host (go run), not on the device:
//
//	go run ./cmd/fontgen          # regenerates fonts/*.bin and fonts/fonts.go
//
// The default font set uses Roboto and Roboto Slab (Apache License 2.0) as
// installed by Fedora's google-roboto-fonts and google-roboto-slab-fonts
// packages; pass -dir to point at another directory with the same files.
package main

import (
	"bytes"
	"encoding/binary"
	"flag"
	"fmt"
	"image"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/image/font"
	"golang.org/x/image/font/opentype"
	"golang.org/x/image/math/fixed"
)

type spec struct {
	name  string // Go identifier
	file  string // TTF file name
	size  float64
	runes string // "" = default set
	doc   string
}

// extra characters beyond ASCII that the UI uses.
const extra = "°·•–—…×←→↑↓▲▼✓"

var specs = []spec{
	{"Sans18", "google-roboto/Roboto-Regular.ttf", 18, "", "Roboto Regular, 18 px: small print"},
	{"Sans22", "google-roboto/Roboto-Regular.ttf", 22, "", "Roboto Regular, 22 px: status bar, captions"},
	{"Sans28", "google-roboto/Roboto-Regular.ttf", 28, "", "Roboto Regular, 28 px: body text"},
	{"SansBold28", "google-roboto/Roboto-Bold.ttf", 28, "", "Roboto Bold, 28 px: buttons, labels"},
	{"SansBold40", "google-roboto/Roboto-Bold.ttf", 40, "", "Roboto Bold, 40 px: titles"},
	{"Serif30", "google-roboto-slab-fonts/RobotoSlab-Regular.ttf", 30, "", "Roboto Slab Regular, 30 px: reading"},
	{"SerifBold36", "google-roboto-slab-fonts/RobotoSlab-Bold.ttf", 36, "", "Roboto Slab Bold, 36 px: headings"},
	{"Digits64", "google-roboto/Roboto-Light.ttf", 64, "0123456789:.-+%° ", "Roboto Light, 64 px, digits only"},
	{"Digits180", "google-roboto/Roboto-Light.ttf", 180, "0123456789: ", "Roboto Light, 180 px, digits and colon only"},
}

func main() {
	dir := flag.String("dir", "/usr/share/fonts", "directory with the font files")
	out := flag.String("out", "fonts", "output directory")
	flag.Parse()

	var src bytes.Buffer
	src.WriteString(`// Code generated by cmd/fontgen; DO NOT EDIT.

// Package fonts holds anti-aliased bitmap fonts for package gfx, rasterized
// from Roboto and Roboto Slab (Copyright Google, Apache License 2.0, see
// LICENSE-fonts) by cmd/fontgen.
package fonts

import (
	_ "embed"

	"tiny-m5papers3/gfx"
)
`)
	total := 0
	for _, s := range specs {
		data, err := build(filepath.Join(*dir, s.file), s)
		if err != nil {
			log.Fatalf("%s: %v", s.name, err)
		}
		file := strings.ToLower(s.name) + ".bin"
		if err := os.WriteFile(filepath.Join(*out, file), data, 0o644); err != nil {
			log.Fatal(err)
		}
		total += len(data)
		fmt.Fprintf(&src, "\n//go:embed %s\nvar %s string\n\n// %s is %s.\nvar %s = gfx.NewFont(%s)\n",
			file, strings.ToLower(s.name), s.name, s.doc, s.name, strings.ToLower(s.name))
		log.Printf("%-12s %6d bytes", s.name, len(data))
	}
	if err := os.WriteFile(filepath.Join(*out, "fonts.go"), src.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("total %d bytes", total)
}

type glyph struct {
	r      rune
	w, h   int
	xoff   int
	top    int // from the baseline, negative = above
	adv    fixed.Int26_6
	bitmap []byte // 4 bits per pixel, rows padded to bytes
}

func build(path string, s spec) ([]byte, error) {
	ttf, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	f, err := opentype.Parse(ttf)
	if err != nil {
		return nil, err
	}
	face, err := opentype.NewFace(f, &opentype.FaceOptions{Size: s.size, DPI: 72, Hinting: font.HintingNone})
	if err != nil {
		return nil, err
	}
	runes := s.runes
	if runes == "" {
		var b strings.Builder
		for r := rune(32); r < 127; r++ {
			b.WriteRune(r)
		}
		b.WriteString(extra)
		runes = b.String()
	}
	var glyphs []glyph
	seen := map[rune]bool{}
	ascent, descent := 0, 0
	for _, r := range runes {
		if seen[r] {
			continue
		}
		seen[r] = true
		if idx, _ := f.GlyphIndex(nil, r); idx == 0 && r != ' ' {
			log.Printf("%s: no glyph for %q, skipped", s.name, r)
			continue
		}
		dr, mask, mp, adv, ok := face.Glyph(fixed.Point26_6{}, r)
		if !ok {
			continue
		}
		g := glyph{r: r, w: dr.Dx(), h: dr.Dy(), xoff: dr.Min.X, top: dr.Min.Y, adv: adv}
		if g.w > 255 || g.h > 255 {
			return nil, fmt.Errorf("glyph %q too large: %dx%d", r, g.w, g.h)
		}
		g.bitmap = pack(mask, mp, g.w, g.h)
		if g.w > 0 {
			ascent = max(ascent, -dr.Min.Y)
			descent = max(descent, dr.Max.Y)
		}
		glyphs = append(glyphs, g)
	}
	sort.Slice(glyphs, func(i, j int) bool { return glyphs[i].r < glyphs[j].r })

	m := face.Metrics()
	lineHeight := max(m.Height.Ceil(), ascent+descent)

	var buf bytes.Buffer
	le := binary.LittleEndian
	hdr := make([]byte, 12)
	hdr[0] = 1 // format version
	le.PutUint16(hdr[2:], uint16(len(glyphs)))
	le.PutUint16(hdr[4:], uint16(ascent))
	le.PutUint16(hdr[6:], uint16(descent))
	le.PutUint16(hdr[8:], uint16(lineHeight))
	le.PutUint16(hdr[10:], uint16(m.Ascent.Ceil())) // nominal ascent
	buf.Write(hdr)
	off := 0
	for _, g := range glyphs {
		rec := make([]byte, 12)
		le.PutUint16(rec[0:], uint16(g.r))
		rec[2], rec[3], rec[4] = byte(off), byte(off>>8), byte(off>>16)
		rec[5], rec[6] = byte(g.w), byte(g.h)
		rec[7] = byte(int8(g.xoff))
		rec[8] = byte(ascent + g.top)               // from the top of the line box
		le.PutUint16(rec[9:], uint16((g.adv+2)>>2)) // 1/16 px
		buf.Write(rec)
		off += len(g.bitmap)
	}
	for _, g := range glyphs {
		buf.Write(g.bitmap)
	}
	if off >= 1<<24 {
		return nil, fmt.Errorf("bitmap data too large")
	}
	return buf.Bytes(), nil
}

// pack converts an alpha mask to 4 bits per pixel, first pixel in the high
// nibble, each row padded to a whole byte.
func pack(mask image.Image, mp image.Point, w, h int) []byte {
	stride := (w + 1) / 2
	out := make([]byte, stride*h)
	for y := 0; y < h; y++ {
		for x := 0; x < w; x++ {
			_, _, _, a := mask.At(mp.X+x, mp.Y+y).RGBA() // 16 bit
			v := byte((a*15 + 0x7fff) / 0xffff)
			if x&1 == 0 {
				out[y*stride+x/2] |= v << 4
			} else {
				out[y*stride+x/2] |= v
			}
		}
	}
	return out
}
